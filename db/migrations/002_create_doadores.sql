CREATE TABLE doadores (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    nome            VARCHAR(120)    NOT NULL,
    cpf             CHAR(11) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    data_nascimento DATE            NOT NULL,
    tipo_sanguineo  VARCHAR(3)      NOT NULL,
    fator_rh        CHAR(1)         NOT NULL,
    sexo            CHAR(1)         NOT NULL,
    peso            DECIMAL(5,2)    NOT NULL,
    telefone        VARCHAR(20)     NULL,
    email           VARCHAR(150)    NULL,
    endereco        VARCHAR(255)    NULL,
    ativo           TINYINT(1)      NOT NULL DEFAULT 1,
    criado_em       DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT uq_doadores_cpf UNIQUE (cpf),
    CONSTRAINT ck_doadores_nome CHECK (CHAR_LENGTH(TRIM(nome)) > 0),
    CONSTRAINT ck_doadores_sexo CHECK (sexo IN ('M', 'F')),
    CONSTRAINT ck_doadores_tipo_sanguineo CHECK (tipo_sanguineo IN ('A', 'B', 'AB', 'O')),
    CONSTRAINT ck_doadores_fator_rh CHECK (fator_rh IN ('+', '-')),
    CONSTRAINT ck_doadores_peso CHECK (peso > 0),
    INDEX ix_doadores_nome (nome)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
